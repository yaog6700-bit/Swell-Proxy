        public static RouteSimulationResult? Evaluate(string? rawInput, IReadOnlyList<RoutingRuleItem>? overrideRules = null)
        {
            if (string.IsNullOrWhiteSpace(rawInput))
                return null;

            ParseTarget(rawInput.Trim(), out string? domain, out IPAddress? ip, out string? procName, out string? procPath);
            if (string.IsNullOrEmpty(domain) && ip == null && string.IsNullOrEmpty(procName))
                return null;

            var session = AppSession.Instance;
            string routingMode = session.RoutingMode ?? "smart";
            bool isRawIpOrProcOnly = string.IsNullOrEmpty(domain);

            string localDnsAddr = !string.IsNullOrEmpty(session.DirectDns) ? session.DirectDns : "223.5.5.5";
            string remoteDnsAddr = !string.IsNullOrEmpty(session.ProxyDns) ? session.ProxyDns : "https://1.1.1.1/dns-query";
            if (session.EnableFakeDns)
                remoteDnsAddr = $"FakeIP + {remoteDnsAddr}";

            string FormatDns(SimulatedOutboundKind kind, bool forceLocal = false)
            {
                if (kind == SimulatedOutboundKind.Block)
                    return L.RouteSim_DnsBlocked;
                if (isRawIpOrProcOnly)
                    return ip != null ? L.RouteSim_DnsDirectSkipped : string.Format(L.RouteSim_DnsRemoteFmt, remoteDnsAddr);
                if (forceLocal || kind == SimulatedOutboundKind.Direct)
                    return string.Format(L.RouteSim_DnsLocalFmt, localDnsAddr);
                return string.Format(L.RouteSim_DnsRemoteFmt, remoteDnsAddr);
            }

            // 1. Built-in private IP / localhost safeguard (applies in ALL routing modes in BuildRoute!)
            if ((ip != null && IsPrivateOrLoopbackIp(ip)) ||
                (!string.IsNullOrEmpty(domain) && (string.Equals(domain, "localhost", StringComparison.OrdinalIgnoreCase) || domain.EndsWith(".local", StringComparison.OrdinalIgnoreCase))))
            {
                return new RouteSimulationResult(
                    SimulatedOutboundKind.Direct,
                    L.Routing_ActionDirect,
                    L.RouteSim_RulePrivateIp,
                    FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
            }

            // 2. Built-in Tailscale route
            if (session.EnableTailscale)
            {
                if ((!string.IsNullOrEmpty(domain) && MatchesDomainSuffix(domain, "ts.net")) ||
                    (ip != null && TryMatchCidr(ip, "100.64.0.0/10")))
                {
                    return new RouteSimulationResult(
                        SimulatedOutboundKind.Direct,
                        "Tailscale",
                        L.RouteSim_RuleTailscale,
                        FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
                }
            }

            // 3. Enterprise Intranet / VPN direct split
            var intranet = WindowsIntranetDetector.Detect();
            if (!string.IsNullOrEmpty(domain) && intranet.DirectDomainSuffixes.Any(s => MatchesDomainSuffix(domain, s)))
            {
                return new RouteSimulationResult(
                    SimulatedOutboundKind.Direct,
                    L.Routing_ActionDirect,
                    L.RouteSim_RuleIntranet,
                    FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
            }
            if (ip != null && intranet.DirectIpCidrs.Any(c => TryMatchCidr(ip, c)))
            {
                return new RouteSimulationResult(
                    SimulatedOutboundKind.Direct,
                    L.Routing_ActionDirect,
                    L.RouteSim_RuleIntranet,
                    FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
            }

            // 4. Global Proxy / Global Direct modes short-circuit right here (matching BuildRoute!)
            if (string.Equals(routingMode, "global", StringComparison.OrdinalIgnoreCase))
            {
                var (kind, label) = ResolveOutboundDisplay("proxy");
                return new RouteSimulationResult(kind, label, L.RouteSim_RuleGlobalMode, FormatDns(kind));
            }

            if (string.Equals(routingMode, "direct", StringComparison.OrdinalIgnoreCase))
            {
                return new RouteSimulationResult(
                    SimulatedOutboundKind.Direct,
                    L.Routing_ActionDirect,
                    L.RouteSim_RuleDirectMode,
                    FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
            }

            // 5. Smart (Rule) Mode: Ad-Block check
            if (session.BlockAds && !string.IsNullOrEmpty(domain) &&
                CommonAdDomainSuffixes.Any(ad => MatchesDomainSuffix(domain, ad)))
            {
                return new RouteSimulationResult(
                    SimulatedOutboundKind.Block,
                    L.Routing_ActionBlock,
                    L.RouteSim_RuleAdBlock,
                    L.RouteSim_DnsBlocked);
            }

            // 6. User Custom Rules first, then Built-in App Rules (exact order from ConfigBuilder.BuildRoute!)
            if (session.EnableAdvancedRouting)
            {
                var allRules = overrideRules ?? RoutingRulesService.LoadRules();
                foreach (var rule in allRules.Where(r => !r.IsBuiltIn && r.IsEnabled))
                {
                    if (TryMatchRoutingRule(rule, domain, ip, procName, procPath, out string matchedExpr))
                    {
                        var (kind, label) = ResolveOutboundDisplay(rule.OutboundTag);
                        string ruleTitle = string.IsNullOrWhiteSpace(rule.Name) ? L.CustomRules_DefaultName : rule.Name;
                        bool cnDns = !string.IsNullOrEmpty(domain) && session.BypassChina && IsLikelyChinaDomain(domain);
                        return new RouteSimulationResult(
                            kind,
                            label,
                            $"{ruleTitle} ({matchedExpr})",
                            FormatDns(kind, forceLocal: cnDns));
                    }
                }

                foreach (var rule in allRules.Where(r => r.IsBuiltIn && r.IsEnabled))
                {
                    if (TryMatchRoutingRule(rule, domain, ip, procName, procPath, out string matchedExpr))
                    {
                        var (kind, label) = ResolveOutboundDisplay(rule.OutboundTag);
                        return new RouteSimulationResult(
                            kind,
                            label,
                            $"{rule.Name} ({matchedExpr})",
                            FormatDns(kind));
                    }
                }
            }

            // 7. Bypass China rules
            if (session.BypassChina && !string.IsNullOrEmpty(domain))
            {
                if (MatchesDomainSuffix(domain, "googleapis.cn") ||
                    MatchesDomainSuffix(domain, "xn--ngstr-lra8j.com") ||
                    MatchesDomainSuffix(domain, "play.googleapis.com"))
                {
                    var (kind, label) = ResolveOutboundDisplay("proxy");
                    return new RouteSimulationResult(kind, label, L.RouteSim_RuleGoogleCn, FormatDns(kind));
                }

                if (IsLikelyChinaDomain(domain))
                {
                    return new RouteSimulationResult(
                        SimulatedOutboundKind.Direct,
                        L.Routing_ActionDirect,
                        L.RouteSim_RuleChinaDirect,
                        FormatDns(SimulatedOutboundKind.Direct, forceLocal: true));
                }
            }

            // 8. Final fallback -> proxy
            var (finalKind, finalLabel) = ResolveOutboundDisplay("proxy");
            return new RouteSimulationResult(finalKind, finalLabel, L.RouteSim_RuleFinalProxy, FormatDns(finalKind));
        }

        private static (SimulatedOutboundKind Kind, string Label) ResolveOutboundDisplay(string? outboundTag)
        {
            string raw = string.IsNullOrWhiteSpace(outboundTag) ? "proxy" : outboundTag.Trim();
            if (raw.StartsWith("node:", StringComparison.Ordinal))
                raw = raw.Substring(5);

            if (string.Equals(raw, "direct", StringComparison.OrdinalIgnoreCase))
                return (SimulatedOutboundKind.Direct, L.Routing_ActionDirect);

            if (string.Equals(raw, "block", StringComparison.OrdinalIgnoreCase) ||
                string.Equals(raw, "reject", StringComparison.OrdinalIgnoreCase))
                return (SimulatedOutboundKind.Block, L.Routing_ActionBlock);

            if (string.Equals(raw, "urltest", StringComparison.OrdinalIgnoreCase))
                return (SimulatedOutboundKind.Proxy, $"{L.Routing_BadgeProxy} · {L.TrayPanel_AutoTitle}");

            var nodes = NodesManager.Instance.GetNodesSnapshot();
            if (!string.Equals(raw, "proxy", StringComparison.OrdinalIgnoreCase))
            {
                var targetNode = nodes.Find(n => n.Id == raw);
                if (targetNode != null)
                    return (SimulatedOutboundKind.Proxy, $"{L.Routing_BadgeProxy} · {targetNode.Name}");
            }

            if (AppSession.Instance.IsAutoNodeSelect)
                return (SimulatedOutboundKind.Proxy, $"{L.Routing_BadgeProxy} · {L.TrayPanel_AutoTitle}");

            var selected = nodes.Find(n => n.Id == NodesManager.Instance.SelectedNodeId);
            if (selected != null && !string.IsNullOrWhiteSpace(selected.Name))
                return (SimulatedOutboundKind.Proxy, $"{L.Routing_BadgeProxy} · {selected.Name}");

            return (SimulatedOutboundKind.Proxy, L.Routing_ActionProxy);
        }

        private static void ParseTarget(
            string input,
            out string? domain,
            out IPAddress? ip,
            out string? procName,
            out string? procPath)
        {
            domain = null;
            ip = null;
            procName = null;
            procPath = null;

            // Process path or executable name
            if (input.EndsWith(".exe", StringComparison.OrdinalIgnoreCase) ||
                (input.Contains('\\') && !input.Contains("://", StringComparison.Ordinal)))
            {
                procPath = input;
                try { procName = Path.GetFileName(input); }
                catch { procName = input; }
                return;
            }

            string candidate = input;
            if (candidate.Contains("://", StringComparison.Ordinal) &&
                Uri.TryCreate(candidate, UriKind.Absolute, out var uri))
            {
                candidate = uri.IdnHost;
            }
            else
            {
                int slashIdx = candidate.IndexOf('/');
                if (slashIdx > 0)
                    candidate = candidate.Substring(0, slashIdx);

                if (NodeLinkParser.TrySplitHostPort(candidate, out var splitHost, out int splitPort) && splitPort > 0)
                    candidate = splitHost;
            }

            candidate = candidate.Trim().Trim('[', ']').TrimEnd('.');
            if (string.IsNullOrEmpty(candidate))
                return;

            if (IPAddress.TryParse(candidate, out var parsedIp))
            {
                ip = parsedIp;
                return;
            }

            domain = candidate.ToLowerInvariant();
        }

        private static bool TryMatchRoutingRule(
            RoutingRuleItem rule,
            string? domain,
            IPAddress? ip,
            string? procName,
            string? procPath,
            out string matchedExpr)
        {
            matchedExpr = string.Empty;
            if (string.IsNullOrWhiteSpace(rule.Match))
                return false;

            string ruleType = (rule.Type ?? "domain").ToLowerInvariant();
            foreach (var rawEntry in SplitEntries(rule.Match))
            {
                string entry = rawEntry.Trim();
                if (entry.Length == 0) continue;

                if (MatchesSingleEntry(ruleType, entry, domain, ip, procName, procPath))
                {
                    matchedExpr = entry;
                    return true;
                }
            }
            return false;
        }

        private static bool MatchesSingleEntry(
            string ruleType,
            string entry,
            string? domain,
            IPAddress? ip,
            string? procName,
            string? procPath)
        {
            if (TryStripPrefix(entry, "geosite:", out var geositeTag))
            {
                if (string.IsNullOrEmpty(domain)) return false;
                if (string.Equals(geositeTag, "cn", StringComparison.OrdinalIgnoreCase))
                    return IsLikelyChinaDomain(domain);
                if (GeositeHints.TryGetValue(geositeTag, out var suffixes))
                    return suffixes.Any(s => MatchesDomainSuffix(domain, s));
                return MatchesDomainSuffix(domain, geositeTag + ".com") || domain.Contains(geositeTag, StringComparison.OrdinalIgnoreCase);
            }

            if (TryStripPrefix(entry, "geoip:", out var geoipTag))
            {
                if (ip == null) return false;
                if (string.Equals(geoipTag, "private", StringComparison.OrdinalIgnoreCase))
                    return IsPrivateOrLoopbackIp(ip);
                return false;
            }

            if (TryStripPrefix(entry, "domain_suffix:", out var suffix))
                return !string.IsNullOrEmpty(domain) && MatchesDomainSuffix(domain, suffix);

            if (TryStripPrefix(entry, "domain:", out var exact))
                return !string.IsNullOrEmpty(domain) && string.Equals(domain, exact.TrimStart('.'), StringComparison.OrdinalIgnoreCase);

            if (TryStripPrefix(entry, "domain_keyword:", out var kw))
                return !string.IsNullOrEmpty(domain) && domain.Contains(kw, StringComparison.OrdinalIgnoreCase);

            if (TryStripPrefix(entry, "domain_regex:", out var rx) ||
                TryStripPrefix(entry, "regex:", out rx) ||
                TryStripPrefix(entry, "regexp:", out rx))
            {
                if (string.IsNullOrEmpty(domain)) return false;
                try { return Regex.IsMatch(domain, rx, RegexOptions.IgnoreCase, TimeSpan.FromMilliseconds(50)); }
                catch { return false; }
            }

            if (TryStripPrefix(entry, "ip_cidr:", out var cidr))
                return ip != null && TryMatchCidr(ip, cidr);

            if (TryStripPrefix(entry, "process_name:", out var pName))
                return !string.IsNullOrEmpty(procName) && string.Equals(procName, pName, StringComparison.OrdinalIgnoreCase);

            if (TryStripPrefix(entry, "process_path:", out var pPath))
                return !string.IsNullOrEmpty(procPath) && string.Equals(procPath, pPath, StringComparison.OrdinalIgnoreCase);

            return ruleType switch
            {
                "ip" => ip != null && TryMatchCidr(ip, entry),
                "process" => (entry.Contains('\\') || entry.Contains('/'))
                    ? (!string.IsNullOrEmpty(procPath) && string.Equals(procPath, entry, StringComparison.OrdinalIgnoreCase))
                    : (!string.IsNullOrEmpty(procName) && string.Equals(procName, entry, StringComparison.OrdinalIgnoreCase)),
                "mixed" => (ip != null && TryMatchCidr(ip, entry)) ||
                           (!string.IsNullOrEmpty(domain) && MatchesDomainSuffix(domain, entry)),
                _ => !string.IsNullOrEmpty(domain) && MatchesDomainSuffix(domain, entry)
            };
        }

        private static bool MatchesDomainSuffix(string domain, string suffix)
        {
            suffix = suffix.Trim().TrimStart('.');
            if (suffix.Length == 0) return false;
            return string.Equals(domain, suffix, StringComparison.OrdinalIgnoreCase) ||
                   domain.EndsWith("." + suffix, StringComparison.OrdinalIgnoreCase);
        }

        private static bool IsLikelyChinaDomain(string domain)
        {
            if (domain.EndsWith(".cn", StringComparison.OrdinalIgnoreCase) ||
                domain.EndsWith(".xn--fiqs8s", StringComparison.OrdinalIgnoreCase) ||
                domain.EndsWith(".中国", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            return CommonCnDomains.Any(cn => MatchesDomainSuffix(domain, cn));
        }

        private static bool IsPrivateOrLoopbackIp(IPAddress ip)
        {
            if (IPAddress.IsLoopback(ip)) return true;

            if (ip.AddressFamily == AddressFamily.InterNetwork)
            {
                byte[] b = ip.GetAddressBytes();
                return b[0] == 10 ||
                       b[0] == 127 ||
                       (b[0] == 172 && b[1] >= 16 && b[1] <= 31) ||
                       (b[0] == 192 && b[1] == 168) ||
                       (b[0] == 169 && b[1] == 254);
            }

            if (ip.AddressFamily == AddressFamily.InterNetworkV6)
            {
                if (ip.IsIPv6LinkLocal || ip.IsIPv6SiteLocal) return true;
                byte[] b = ip.GetAddressBytes();
                return (b[0] & 0xFE) == 0xFC; // fc00::/7 Unique Local
            }

            return false;
        }

        private static bool TryMatchCidr(IPAddress address, string cidrOrIp)
        {
            string clean = cidrOrIp.Trim();
            int slash = clean.IndexOf('/');
            string ipStr = slash >= 0 ? clean.Substring(0, slash) : clean;
            if (!IPAddress.TryParse(ipStr, out var networkIp))
                return false;

            if (networkIp.AddressFamily != address.AddressFamily)
                return false;

            byte[] addrBytes = address.GetAddressBytes();
            byte[] netBytes = networkIp.GetAddressBytes();
            int maxBits = addrBytes.Length * 8;
            int prefixLen = maxBits;

            if (slash >= 0 && (!int.TryParse(clean.Substring(slash + 1), out prefixLen) || prefixLen < 0 || prefixLen > maxBits))
                return false;

            int fullBytes = prefixLen / 8;
            int remBits = prefixLen % 8;

            for (int i = 0; i < fullBytes; i++)
            {
                if (addrBytes[i] != netBytes[i]) return false;
            }

            if (remBits > 0)
            {
                int mask = 0xFF << (8 - remBits);
                if ((addrBytes[fullBytes] & mask) != (netBytes[fullBytes] & mask))
                    return false;
            }

            return true;
        }

        private static bool TryStripPrefix(string input, string prefix, out string rest)
        {
            if (input.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
            {
                rest = input.Substring(prefix.Length).Trim();
                return rest.Length > 0;
            }
            rest = string.Empty;
            return false;
        }

        private static List<string> SplitEntries(string match)
        {
            var result = new List<string>();
            int braceDepth = 0;
            int start = 0;
            for (int i = 0; i < match.Length; i++)
            {
                char c = match[i];
                if (c == '\\' && i + 1 < match.Length) { i++; continue; }
                if (c == '{') braceDepth++;
                else if (c == '}' && braceDepth > 0) braceDepth--;
                else if (c == ',' && braceDepth == 0)
                {
                    var piece = match.Substring(start, i - start).Trim();
                    if (piece.Length > 0) result.Add(piece);
                    start = i + 1;
                }
            }
            if (start < match.Length)
            {
                var tail = match.Substring(start).Trim();
                if (tail.Length > 0) result.Add(tail);
            }
            return result;
        }
